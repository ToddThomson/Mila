    template<typename TPrecisionTag>
    class GatedDeltaRuleCudaTests : public ::testing::Test
    {
    protected:
        static constexpr TensorDataType P = TPrecisionTag::value;

        using RuleType = Mila::Dnn::GatedDeltaRule<DeviceType::Cuda, P>;
        using DeviceTensor = Tensor<P, CudaDeviceMemoryResource>;
        using HostFp32 = Tensor<TensorDataType::FP32, CpuMemoryResource>;

        void SetUp() override
        {
            try
            {
                cuda_context_ = createExecutionContext( Device::Cuda( 0 ) );
            }
            catch ( const std::exception& )
            {
                cuda_context_ = nullptr;
            }

            if ( !cuda_context_ )
            {
                GTEST_SKIP() << "CUDA device not available";
            }
        }

        static GatedDeltaRuleConfig config()
        {
            return GatedDeltaRuleConfig( kKeyHeads, kValueHeads, kHeadKeyDim, kHeadValueDim );
        }

        std::unique_ptr<RuleType> builtRule( dim_t steps )
        {
            auto rule = std::make_unique<RuleType>( "delta_rule", config(), Device::Cuda( 0 ) );
            rule->build( BuildContext( shape_t{ kBatch, steps, kValueWidth }, RuntimeMode::Inference, false ) );

            auto parameters = rule->getParameters();
            copy( hostFrom( kALog, shape_t{ kValueHeads } ),
                *static_cast<DeviceTensor*>( parameters[ 0 ] ), cuda_context_.get() );
            copy( hostFrom( kDtBias, shape_t{ kValueHeads } ),
                *static_cast<DeviceTensor*>( parameters[ 1 ] ), cuda_context_.get() );
            cuda_context_->synchronize();

            return rule;
        }

        HostFp32 hostFrom( const float* source, const shape_t& shape )
        {
            HostFp32 host( Device::Cpu(), shape );

            for ( dim_t i = 0; i < host.size(); ++i )
            {
                host.data()[ i ] = source[ i ];
            }

            return host;
        }

        /// A [kBatch, count, width] slice of a whole-sequence array, starting at `start`.
        HostFp32 hostSlice( const float* source, dim_t width, dim_t start, dim_t count )
        {
            HostFp32 host( Device::Cpu(), shape_t{ kBatch, count, width } );

            for ( dim_t t = 0; t < count; ++t )
            {
                for ( dim_t w = 0; w < width; ++w )
                {
                    host.data()[ t * width + w ] = source[ (start + t) * width + w ];
                }
            }

            return host;
        }

        DeviceTensor toDevice( const HostFp32& host )
        {
            DeviceTensor device( Device::Cuda( 0 ), host.shape() );
            copy( host, device, cuda_context_.get() );
            cuda_context_->synchronize();

            return device;
        }

        HostFp32 toFloat( const DeviceTensor& device )
        {
            auto host = toHost<TensorDataType::FP32>( device, cuda_context_.get() );
            cuda_context_->synchronize();

            return host;
        }

        std::unique_ptr<IExecutionContext> cuda_context_;
    };

