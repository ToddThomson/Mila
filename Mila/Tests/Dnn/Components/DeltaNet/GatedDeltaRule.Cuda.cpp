    /**
     * @brief Positive control for the two equivalences above.
     *
     * They would also pass against a rule that carried no state at all if the inputs
     * happened not to depend on history. Running the tail as a FRESH sequence must diverge
     * from the whole-sequence answer -- if it ever stops diverging, the equivalences have
     * stopped distinguishing a carried state from a discarded one.
     */
    TYPED_TEST( GatedDeltaRuleCudaTests, DiscardingTheStateChangesTheContinuation )
    {
        constexpr dim_t kFirst = 2;
        constexpr dim_t kSecond = kSteps - kFirst;

        auto rule = this->builtRule( kSecond );

        auto q2 = this->toDevice( this->hostSlice( kQ, kKeyWidth, kFirst, kSecond ) );
        auto k2 = this->toDevice( this->hostSlice( kK, kKeyWidth, kFirst, kSecond ) );
        auto v2 = this->toDevice( this->hostSlice( kV, kValueWidth, kFirst, kSecond ) );
        auto a2 = this->toDevice( this->hostSlice( kA, kValueHeads, kFirst, kSecond ) );
        auto b2 = this->toDevice( this->hostSlice( kB, kValueHeads, kFirst, kSecond ) );

        // position_offset 0 means "this is the start", which zeroes the state.
        auto& fresh_device = rule->prefill( q2, k2, v2, a2, b2, 0 );
        rule->synchronize();
        auto fresh = this->toFloat( fresh_device );

        float max_divergence = 0.0f;

        for ( dim_t i = 0; i < kSecond * kValueWidth; ++i )
        {
            max_divergence = std::max( max_divergence,
                std::fabs( fresh.data()[ i ] - kExpectedOut[ kFirst * kValueWidth + i ] ) );
        }

        // ABSOLUTE, not a multiple of atol. How far the two answers separate is a property
        // of these inputs (measured 0.2197, the same in both precisions), not of the
        // storage type -- scaling the bar by a per-precision tolerance moves the bar above
        // the signal in the looser arm and the control fails for the wrong reason. 0.05
        // clears BF16's 2e-2 noise floor and sits well under the real divergence.
        EXPECT_GT( max_divergence, 0.05f )
            << "discarding the recurrent state changed nothing -- the equivalence tests "
               "above cannot be distinguishing a carried state from a discarded one";
    }

    // ====================================================================
    // C2. The chunked prefill kernel, against the recurrent one
    //
    // Past 32 steps the launcher takes the chunked (UT-transform) kernel; at or below it,
    // and at every decode step, the sequential recurrence. So the tests above pin the
    // recurrent form against the Python oracle, and these pin the chunked form against the
    // recurrent form -- which is Phase 3's exit criterion stated as a test.
    //
    // The two are NOT bit-identical and cannot be: the chunked form sums the same terms in
    // a different order. FP32 is checked at 1e-4 rather than the 1e-5 the oracle tests use.
    // ====================================================================
    namespace
    {
        constexpr dim_t kChunkThreshold = 32;

        /// Bounded and non-repeating across the width, so no two heads see the same signal.
        float syntheticValue( dim_t index, int seed )
        {
            const dim_t step = (index * 37 + static_cast<dim_t>( seed ) * 101) % 211;

            return static_cast<float>( step ) / 105.0f - 1.0f;
        }
    }

